last_reply_time = {}
me = None  # پس از اتصال به سرور پر می‌شود


def pick_reply(text: str) -> str:
    """انتخاب هوشمندانه پاسخ متناسب با کلمات کلیدی پیام دریافتی کاربر"""
    low = (text or "").lower()
    for keys, replies in KEYWORDS.items():
        if any(k.lower() in low for k in keys):
            return random.choice(replies)
    return random.choice(GENERIC)


client = SoroushClient(StringSession(SESSION_STRING))


@client.on(events.NewMessage(incoming=True))
async def on_message(event):
    try:
        global me
        if me is None:
            me = await client.get_me()

        sender = await event.get_sender()
        if sender is None or getattr(sender, "bot", False):
            return

        # ——— بررسی شرایط تریگر برای پاسخ‌دهی انسانی ———
        should_reply = False

        # ۱. پیام خصوصی (PV)
        if event.is_private:
            should_reply = True

        # ۲. منشن شدن در گروه‌ها
        elif getattr(event, "mentioned", False):
            should_reply = True

        # ۳. ریپلای مستقیم به پیام سلف‌بات
        elif event.is_reply:
            replied = await event.get_reply_message()
            if replied and replied.out:
                should_reply = True

        if not should_reply:
            return

        # ——— اعمال سیستم کول‌داون (Cooldown) برای جلوگیری از اسپم ———
        now = time.time()
        uid = sender.id
        if now - last_reply_time.get(uid, 0) < COOLDOWN_PER_USER:
            return
        last_reply_time[uid] = now

        # ——— شبیه‌سازی ری‌اکشن انسانی به پیام کاربر ———
        try:
            if random.random() > 0.2:  # در ۸۰ درصد مواقع روی پیام ری‌اکشن هم می‌گذارد
                chosen_reaction = random.choice(POSSIBLE_REACTIONS)
                await event.react(chosen_reaction)
        except Exception:
            pass

        # ——— شبیه‌سازی تاخیر طبیعی تایپ کردن ———
        await asyncio.sleep(random.uniform(*DELAY_RANGE))
        
        # ارسال پاسخ نهایی
        await event.reply(pick_reply(event.raw_text))

    except Exception as e:
        print("خطای غیرمنتظره در پردازش پیام:", e, flush=True)


