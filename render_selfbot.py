last_reply_time = {}
me = None  # بعد از استارت پر می‌شه


def pick_reply(text: str) -> str:
    low = (text or "").lower()
    for keys, replies in KEYWORDS.items():
        if any(k.lower() in low for k in keys):
            return random.choice(replies)
    return random.choice(GENERIC)


client = SoroushClient(StringSession(SESSION_STRING))


@client.on(events.NewMessage(incoming=True))
async def on_message(event):
    try:
        global me
        if me is None:
            me = await client.get_me()

        sender = await event.get_sender()
        if sender is None or getattr(sender, "bot", False):
            return

        # ——— شرایط تریگر ———
        should_reply = False

        # ۱. پیام خصوصی
        if event.is_private:
            should_reply = True

        # ۲. منشن شده
        elif getattr(event, "mentioned", False):
            should_reply = True

        # ۳. ریپلای به پیام خودم
        elif event.is_reply:
            replied = await event.get_reply_message()
            if replied and replied.out:
                should_reply = True

        if not should_reply:
            return

        # کول‌داون
        now = time.time()
        uid = sender.id
        if now - last_reply_time.get(uid, 0) < COOLDOWN_PER_USER:
            return
        last_reply_time[uid] = now

        # تأخیر تصادفی
        await asyncio.sleep(random.uniform(*DELAY_RANGE))
        await event.reply(pick_reply(event.raw_text))

    except Exception as e:
        print("خطا:", e, flush=True)


# ---------- وب‌سرور و پینگ ----------
async def health(request):
    return web.Response(text="ok")


async def start_web():
    app = web.Application()
    app.router.add_get("/", health)
    runner = web.AppRunner(app)
    await runner.setup()
    await web.TCPSite(runner, "0.0.0.0", PORT).start()
    print(f"وب‌سرور روی پورت {PORT} بالا اومد", flush=True)


async def keep_alive():
    if not PUBLIC_URL:
        print("RENDER_EXTERNAL_URL تنظیم نشده؛ پینگ خودکار غیرفعاله.", flush=True)
        return
    timeout = ClientTimeout(total=30)
    while True:
        await asyncio.sleep(PING_INTERVAL)
        try:
            async with ClientSession(timeout=timeout) as s:
                async with s.get(PUBLIC_URL) as r:
                    print("ping:", r.status, flush=True)
        except Exception as e:
            print("ping خطا:", e, flush=True)


async def main():
    if not SESSION_STRING:
        raise SystemExit("متغیر SESSION_STRING تنظیم نشده.")
    await start_web()
    asyncio.create_task(keep_alive())
    await client.start()
    global me
    me = await client.get_me()
    print("بات فعاله:", getattr(me, "first_name", ""), flush=True)
    await client.run_until_disconnected()


if __name__ == "__main__":
    asyncio.run(main())