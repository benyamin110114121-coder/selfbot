async def health(request):
    return web.Response(text="Soroush Smart Self-Bot Maximum Double Edition is active and running perfectly!")


async def start_web():
    app = web.Application()
    app.router.add_get("/", health)
    runner = web.AppRunner(app)
    await runner.setup()
    await web.TCPSite(runner, "0.0.0.0", PORT).start()
    print(f"وب‌سرور داخلی روی پورت {PORT} با موفقیت راه‌اندازی شد.", flush=True)


async def keep_alive():
    """پینگ دوره‌ای برای جلوگیری از خواب رفتن سرور روی هاست‌های رایگان مثل Render"""
    if not PUBLIC_URL:
        print("هشدار: متغیر RENDER_EXTERNAL_URL تنظیم نشده است؛ پینگ خودکار فعال نیست.", flush=True)
        return
    timeout = ClientTimeout(total=30)
    while True:
        await asyncio.sleep(PING_INTERVAL)
        try:
            async with ClientSession(timeout=timeout) as s:
                async with s.get(PUBLIC_URL) as r:
                    print(f"پینگ خودکار انجام شد - کد وضعیت سرور: {r.status}", flush=True)
        except Exception as e:
            print("خطا در پینگ خودکار سرور:", e, flush=True)


